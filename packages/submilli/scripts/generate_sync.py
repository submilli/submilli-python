"""Generate the sync client, `src/submilli/_client.py`, from the async one.

Run it after changing `_async_client.py`. `--check` fails when the sync client
is out of date, as CI does.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "submilli" / "_async_client.py"
DST = ROOT / "src" / "submilli" / "_client.py"

HEADER = "# Generated by scripts/generate_sync.py from _async_client.py. Do not edit.\n"

t = SRC.read_text()
for a, b_ in [
    (
        '"""`AsyncSubmilli`: the HTTP API of one submilli-server, for asyncio."""',
        '"""`Submilli`: the HTTP API of one submilli-server. The same surface as `AsyncSubmilli`, blocking."""',
    ),
    ("AsyncSubmilli", "Submilli"),
    ("AsyncSessions", "Sessions"),
    ("AsyncRuns", "Runs"),
    ("AsyncBlueprints", "Blueprints"),
    ("AsyncToolHandler", "ToolHandler"),
    ("async def __aenter__", "def __enter__"),
    ("async def __aexit__", "def __exit__"),
    ("async def aclose", "def close"),
    (".aclose()", ".close()"),
    ("async def ", "def "),
    ("await asyncio.sleep", "time.sleep"),
    ("await ", ""),
    ("httpx.AsyncClient", "httpx.Client"),
    ("`aclose`", "`close`"),
    ("async with", "with"),
]:
    t = t.replace(a, b_)


def trep(a: str, b_: str) -> None:
    global t
    assert t.count(a) == 1, a
    t = t.replace(a, b_)


trep(
    """import asyncio
import inspect
from collections.abc import Awaitable, Callable, Mapping, Sequence""",
    """import time
from collections.abc import Callable, Mapping, Sequence""",
)
trep(
    """ToolHandler = Callable[[PendingCall], "ToolResult | Awaitable[ToolResult]"]""",
    """ToolHandler = Callable[[PendingCall], ToolResult]""",
)
trep(
    """            Without one, the client keeps one per event loop and closes it in
            `close`.""",
    """            Without one, the client opens one and closes it in `close`.""",
)
trep(
    """        self._external = http_client
        # An httpx client can't outlive the loop it was first used on, and
        # applications and tests often run several loops.
        self._clients: dict[asyncio.AbstractEventLoop, httpx.Client] = {}
""",
    """        self._external = http_client
        self._client: httpx.Client | None = None
""",
)
trep(
    """        clients, self._clients = list(self._clients.values()), {}
        for client in clients:
            if not client.is_closed:
                client.close()""",
    """        client, self._client = self._client, None
        if client is not None:
            client.close()""",
)
trep(
    """        loop = asyncio.get_running_loop()
        for stale in [other for other in self._clients if other.is_closed()]:
            del self._clients[stale]
        client = self._clients.get(loop)
        if client is None:
            client = httpx.Client(timeout=self._settings.timeout)
            self._clients[loop] = client
        return client""",
    """        if self._client is None:
            self._client = httpx.Client(timeout=self._settings.timeout)
        return self._client""",
)
trep("`on_tool_call`, sync or async, and its", "`on_tool_call`, and its")
trep(
    """                result = on_tool_call(call)
                if inspect.isawaitable(result):
                    result = result
""",
    """                result = on_tool_call(call)
""",
)
t = HEADER + t
# Format as the repository does, so the check compares like with like.
t = subprocess.run(
    ["ruff", "format", "--stdin-filename", str(DST), "-"], input=t, capture_output=True, text=True, check=True
).stdout
if "--check" in sys.argv:
    if DST.read_text() != t:
        sys.exit("src/submilli/_client.py is out of date: run scripts/generate_sync.py")
else:
    DST.write_text(t)
